function buildAnatomyTree(parts: string[]): string {
  if (parts.length === 0) return ''
  if (parts.length === 1) return parts[0]

  const [root, ...rest] = parts
  const lines = [root]

  const childPartRe =
    /(Item|Group|Separator|Empty|Header|Footer|Title|Description|Close|Option|Row|Cell)/

  const contentIndex = rest.findIndex((p) =>
    /(Content|Panel|List|Viewport|Popup)$/.test(p),
  )

  const topLevelFlags = rest.map((part, index) => {
    const isUnderContent =
      contentIndex !== -1 && index > contentIndex && childPartRe.test(part)
    return !isUnderContent
  })

  const lastTopIndex = topLevelFlags.lastIndexOf(true)

  rest.forEach((part, index) => {
    const isTop = topLevelFlags[index]
    if (!isTop) {
      const nextIsChild =
        index + 1 < rest.length && !topLevelFlags[index + 1]
      const branch = nextIsChild ? '├── ' : '└── '
      const parentContinues = lastTopIndex > contentIndex
      lines.push(`${parentContinues ? '│   ' : '    '}${branch}${part}`)
    } else {
      lines.push(`${index === lastTopIndex ? '└── ' : '├── '}${part}`)
    }
  })

  return lines.join('\n')
}

function buildUsageSnippet(
  partNames: string[],
  demoTsx?: string | null,
): { usageSnippet: string; usedParts: string[] } {
  if (partNames.length === 0) return { usageSnippet: '', usedParts: [] }

  const root = partNames[0]
  const has = (suffix: string) => partNames.includes(`${root}${suffix}`)
  const part = (suffix: string) => `${root}${suffix}`

  // If the demo uses `<Root ... />` self-closing (e.g. Calendar, Input, Switch, Slider),
  // show the clean one-liner.
  if (demoTsx && new RegExp(`<${escapeRegExp(root)}(?:\\s[^>]*)?/>`).test(demoTsx)) {
    return { usageSnippet: `<${root} />`, usedParts: [root] }
  }

  if (partNames.length === 1) {
    return {
      usageSnippet: `<${root}>${root}</${root}>`,
      usedParts: [root],
    }
  }

  const used = new Set<string>([root])
  const lines: string[] = [`<${root}>`]

  // Tabs pattern: List -> Tab + Panel
  if (has('List') && has('Tab') && has('Panel')) {
    used.add(part('List'))
    used.add(part('Tab'))
    used.add(part('Panel'))
    lines[0] = `<${root} defaultValue="one">`
    lines.push(`  <${part('List')}>`)
    lines.push(`    <${part('Tab')} value="one">Tab 1</${part('Tab')}>`)
    lines.push(`    <${part('Tab')} value="two">Tab 2</${part('Tab')}>`)
    lines.push(`  </${part('List')}>`)
    lines.push(`  <${part('Panel')} value="one">Panel content</${part('Panel')}>`)
  } else if (has('Trigger') && has('Content')) {
    // Overlay / popup pattern (Dialog, Popover, Select, Menu, Tooltip, Drawer, etc.)
    used.add(part('Trigger'))
    used.add(part('Content'))
    if (has('Value')) {
      used.add(part('Value'))
      lines.push(`  <${part('Trigger')}>`)
      lines.push(`    <${part('Value')} placeholder="Select..." />`)
      lines.push(`  </${part('Trigger')}>`)
    } else {
      lines.push(`  <${part('Trigger')}>Open</${part('Trigger')}>`)
    }
    lines.push(`  <${part('Content')}>`)
    if (has('Title')) {
      used.add(part('Title'))
      lines.push(`    <${part('Title')}>Title</${part('Title')}>`)
    }
    if (has('Description')) {
      used.add(part('Description'))
      lines.push(`    <${part('Description')}>Description</${part('Description')}>`)
    }
    if (has('Item')) {
      used.add(part('Item'))
      lines.push(`    <${part('Item')} value="one">Option 1</${part('Item')}>`)
      lines.push(`    <${part('Item')} value="two">Option 2</${part('Item')}>`)
    } else if (!has('Title') && !has('Description')) {
      lines.push(`    Content`)
    }
    lines.push(`  </${part('Content')}>`)
  } else if (has('Input') && has('Content')) {
    // Combobox / Autocomplete / Command pattern
    used.add(part('Input'))
    used.add(part('Content'))
    lines.push(`  <${part('Input')} placeholder="Search..." />`)
    lines.push(`  <${part('Content')}>`)
    if (has('Item')) {
      used.add(part('Item'))
      lines.push(`    <${part('Item')} value="one">Option 1</${part('Item')}>`)
      lines.push(`    <${part('Item')} value="two">Option 2</${part('Item')}>`)
    }
    lines.push(`  </${part('Content')}>`)
  } else if (has('Item') && has('Trigger') && has('Panel')) {
    // Accordion pattern
    used.add(part('Item'))
    used.add(part('Trigger'))
    used.add(part('Panel'))
    lines.push(`  <${part('Item')} value="one">`)
    lines.push(`    <${part('Trigger')}>Item 1</${part('Trigger')}>`)
    lines.push(`    <${part('Panel')}>Panel content</${part('Panel')}>`)
    lines.push(`  </${part('Item')}>`)
  } else if (has('Trigger') && has('Panel')) {
    // Collapsible pattern
    used.add(part('Trigger'))
    used.add(part('Panel'))
    lines.push(`  <${part('Trigger')}>Toggle</${part('Trigger')}>`)
    lines.push(`  <${part('Panel')}>Panel content</${part('Panel')}>`)
  } else if (has('Item')) {
    // Group / List pattern (SegmentedControl, RadioGroup, Listbox, Tree, Timeline, etc.)
    used.add(part('Item'))
    lines.push(`  <${part('Item')} value="one">Item 1</${part('Item')}>`)
    lines.push(`  <${part('Item')} value="two">Item 2</${part('Item')}>`)
  } else {
    // Fallback: include up to 3 direct subparts
    for (const sub of partNames.slice(1, 4)) {
      used.add(sub)
      lines.push(`  <${sub} />`)
    }
  }

  lines.push(`</${root}>`)
  const usedParts = partNames.filter((name) => used.has(name))
  return { usageSnippet: lines.join('\n'), usedParts }
}

/**
 * Automatically extracts exported parts, custom prop definitions, composition
 * anatomy, CSS `data-*` attributes, and component CSS custom properties from
 * the component's `.tsx` and `.css` source files.
 */
export function extractComponentMeta(
  uiTsx: string | null,
  uiCss: string | null,
  slug: string,
  demoTsx?: string | null,
): ComponentMeta {
  const partNames: string[] = []
  const partPropsMap = new Map<string, ComponentPropDoc[]>()

  if (uiTsx) {
    // 1. Find exported component functions (PascalCase)
    const fnRe = /export\s+function\s+([A-Z][A-Za-z0-9]*)\s*\(/g
    let m: RegExpExecArray | null
    while ((m = fnRe.exec(uiTsx)) !== null) {
      if (!partNames.includes(m[1])) {
        partNames.push(m[1])
      }
    }

    // 2. Parse exported Props types for custom JSDoc-annotated props
    const typeRe =
      /export\s+type\s+([A-Z][A-Za-z0-9]*)Props\s*=\s*[\s\S]*?\{([\s\S]*?)\n\}/g
    while ((m = typeRe.exec(uiTsx)) !== null) {
      const partName = m[1]
      const body = m[2]
      const props: ComponentPropDoc[] = []

      const lines = body.split('\n')
      let pendingDoc = ''
      for (const rawLine of lines) {
        const line = rawLine.trim()
        if (!line) continue
        if (line.startsWith('/**')) {
          pendingDoc = line
            .replace(/^\/\*\*\s*/, '')
            .replace(/\s*\*\/$/, '')
            .trim()
          continue
        }
        if (line.startsWith('*')) {
          const text = line
            .replace(/^\*\s?/, '')
            .replace(/\s*\*\/$/, '')
            .trim()
          if (text) pendingDoc = pendingDoc ? `${pendingDoc} ${text}` : text
          continue
        }
        const propMatch = line.match(/^([a-zA-Z0-9_]+)(\?)?\s*:\s*(.+?);?$/)
        if (propMatch) {
          const [, name, , type] = propMatch
          if (name === 'class' || name === 'render' || name === 'children') {
            pendingDoc = ''
            continue
          }
          props.push({
            name,
            type: type.trim(),
            description: pendingDoc,
          })
          pendingDoc = ''
        }
      }

      if (props.length > 0) {
        partPropsMap.set(partName, props)
      }
    }
  }

  const parts: ComponentPartDoc[] = partNames.map((name) => ({
    name,
    props: partPropsMap.get(name) ?? [],
  }))

  const slots = new Set<string>()
  const attrValues = new Map<string, Set<string>>()
  const cssVars = new Set<string>()

  if (uiCss) {
    // Extract [data-slot="..."] (skip legacy upstream -v2- aliases)
    const slotRe = /\[data-slot=["']([^"']+)["']\]/g
    let m: RegExpExecArray | null
    while ((m = slotRe.exec(uiCss)) !== null) {
      if (!m[1].includes('-v2-')) {
        slots.add(m[1])
      }
    }

    // Extract [data-xyz] and [data-xyz="value"]
    const ignoredAttrs = new Set([
      'data-slot',
      'data-color-scheme',
      'data-component',
      'data-popper-positioner',
    ])
    const attrRe = /\[(data-[a-z0-9-]+)(?:=["']([^"']+)["'])?\]/g
    while ((m = attrRe.exec(uiCss)) !== null) {
      const attr = m[1]
      const val = m[2]
      if (ignoredAttrs.has(attr)) continue
      let set = attrValues.get(attr)
      if (!set) {
        set = new Set<string>()
        attrValues.set(attr, set)
      }
      if (val) set.add(val)
    }

    // Extract component-level CSS custom properties (excluding global --v2-*, --oc-*, --font-*)
    const varRe = /--([a-z][a-z0-9-]*)/g
    while ((m = varRe.exec(uiCss)) !== null) {
      const full = `--${m[1]}`
      if (
        full.startsWith('--v2-') ||
        full.startsWith('--oc-') ||
        full.startsWith('--font-') ||
        full.startsWith('--line-height-') ||
        full.startsWith('--letter-spacing-')
      ) {
        continue
      }
      cssVars.add(full)
    }
  }

  const dataAttributes: DataAttributeDoc[] = Array.from(attrValues.entries())
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([attribute, values]) => ({
      attribute,
      values: Array.from(values).sort(),
      description:
        KNOWN_ATTR_DESCRIPTIONS[attribute] ??
        `Styling hook controlled by the component's ${attribute.replace('data-', '')} state.`,
    }))

  const { usageSnippet, usedParts } = buildUsageSnippet(partNames, demoTsx)
  const importNames = usedParts.length > 0 ? usedParts : partNames

  const importList =
    importNames.length > 3
      ? `{\n  ${importNames.join(',\n  ')},\n}`
      : `{ ${importNames.join(', ')} }`

  const importSnippet =
    importNames.length > 0
      ? `import ${importList} from '#/components/ui/${slug}'`
      : `import * as Component from '#/components/ui/${slug}'`

  return {
    parts,
    slots: Array.from(slots),
    anatomy: buildAnatomyTree(partNames),
    importSnippet,
    usageSnippet,
    dataAttributes,
    cssVariables: Array.from(cssVars).sort(),
  }
}
