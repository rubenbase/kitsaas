/**
 * Automatic source code and metadata discovery for Kitsaas docs.
 *
 * Uses lazy Vite `?raw` globs so only the currently visited component's
 * `.tsx`, `.css`, and demo source files are loaded on demand. From those raw
 * sources, this module automatically derives:
 * - Per-example JSX snippets for every `<Group label="...">` in a demo file
 * - Exported component parts, prop types, and an ASCII composition tree
 * - Styling data attributes (`data-slot`, `data-*`) and CSS variables
 */

const uiTsxModules = import.meta.glob<string>('/src/components/ui/*.tsx', {
  query: '?raw',
  import: 'default',
})

const uiCssModules = import.meta.glob<string>('/src/components/ui/*.css', {
  query: '?raw',
  import: 'default',
})

const demoTsxModules = import.meta.glob<string>(
  '/src/routes/components/demos/*.tsx',
  {
    query: '?raw',
    import: 'default',
  },
)

export type ComponentSources = {
  slug: string
  uiTsx: string | null
  uiCss: string | null
  demoTsx: string | null
}

export type RegistryItemFile = {
  path: string
  type: string
  target?: string
  content: string
}

export type RegistryItemJson = {
  name: string
  type: string
  title?: string
  description?: string
  dependencies?: string[]
  registryDependencies?: string[]
  files: RegistryItemFile[]
}

const registryItemCache = new Map<string, Promise<RegistryItemJson | null>>()

/**
 * Fetches the built shadcn registry-item.json for a given framework & component
 * from `/r/<framework>/<slug>.json` (generated by `pnpm registry:build`).
 */
export function loadRegistryItem(
  framework: string,
  slug: string,
): Promise<RegistryItemJson | null> {
  const key = `${framework}:${slug}`
  const cached = registryItemCache.get(key)
  if (cached) return cached

  const promise = (async () => {
    try {
      const response = await fetch(`/r/${framework}/${slug}.json`)
      if (!response.ok) return null
      return (await response.json()) as RegistryItemJson
    } catch {
      return null
    }
  })()

  registryItemCache.set(key, promise)
  return promise
}

export type ComponentPropDoc = {
  name: string
  type: string
  description: string
}

export type ComponentPartDoc = {
  name: string
  props: ComponentPropDoc[]
}

export type DataAttributeDoc = {
  attribute: string
  values: string[]
  description: string
}

export type ComponentMeta = {
  parts: ComponentPartDoc[]
  slots: string[]
  anatomy: string
  importSnippet: string
  usageSnippet: string
  dataAttributes: DataAttributeDoc[]
  cssVariables: string[]
}

const sourceCache = new Map<string, Promise<ComponentSources>>()

export function loadComponentSources(slug: string): Promise<ComponentSources> {
  const cached = sourceCache.get(slug)
  if (cached) return cached

  const load = async (): Promise<ComponentSources> => {
    const uiTsxLoader = uiTsxModules[`/src/components/ui/${slug}.tsx`]
    const uiCssLoader = uiCssModules[`/src/components/ui/${slug}.css`]
    const demoTsxLoader =
      demoTsxModules[`/src/routes/components/demos/${slug}.tsx`]

    const [uiTsx, uiCss, demoTsx] = await Promise.all([
      uiTsxLoader ? uiTsxLoader() : Promise.resolve(null),
      uiCssLoader ? uiCssLoader() : Promise.resolve(null),
      demoTsxLoader ? demoTsxLoader() : Promise.resolve(null),
    ])

    return { slug, uiTsx, uiCss, demoTsx }
  }

  const promise = load()
  sourceCache.set(slug, promise)
  return promise
}

function dedent(raw: string): string {
  const lines = raw.replace(/\r\n/g, '\n').split('\n')
  while (lines.length && lines[0].trim() === '') lines.shift()
  while (lines.length && lines[lines.length - 1].trim() === '') lines.pop()

  let minIndent = Infinity
  for (const line of lines) {
    if (!line.trim()) continue
    const match = line.match(/^\s*/)
    if (match && match[0].length < minIndent) {
      minIndent = match[0].length
    }
  }
  if (!Number.isFinite(minIndent) || minIndent === 0) {
    return lines.join('\n')
  }
  return lines.map((line) => line.slice(minIndent)).join('\n')
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/**
 * Extracts a clean, copyable Solid JSX snippet for `<Group label="...">` from
 * the component's raw demo file, keeping only the relevant imports.
 */
export function extractGroupSnippet(
  demoSource: string | null,
  label: string,
): string | null {
  if (!demoSource) return null

  const pattern = new RegExp(
    `<Group\\b[^>]*\\blabel=(?:"${escapeRegExp(label)}"|'${escapeRegExp(label)}')[^>]*>`,
  )
  const openMatch = pattern.exec(demoSource)
  if (!openMatch) return null

  const bodyStart = openMatch.index + openMatch[0].length
  let depth = 1
  let cursor = bodyStart

  const tagRe = /<\/?Group\b[^>]*>/g
  tagRe.lastIndex = bodyStart

  let bodyEnd = -1
  while (depth > 0) {
    const next = tagRe.exec(demoSource)
    if (!next) break
    const token = next[0]
    if (token.startsWith('</Group')) {
      depth -= 1
      if (depth === 0) {
        bodyEnd = next.index
        break
      }
    } else if (!token.endsWith('/>')) {
      depth += 1
    }
    cursor = tagRe.lastIndex
  }

  if (bodyEnd === -1 || bodyEnd < cursor - 100000) return null

  const inner = dedent(demoSource.slice(bodyStart, bodyEnd))
  if (!inner) return null

  // Collect matching import statements used in the extracted snippet.
  const importRe = /^import\s+(?:type\s+)?\{([^}]+)\}\s+from\s+['"]([^'"]+)['"]/gm
  const imports: string[] = []
  let imp: RegExpExecArray | null
  while ((imp = importRe.exec(demoSource)) !== null) {
    const mod = imp[2]
    if (mod.startsWith('./') || mod.startsWith('../')) continue
    const specifiers = imp[1]
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
      .filter((spec) => {
        const clean = spec
          .replace(/^type\s+/, '')
          .split(/\s+as\s+/)
          .pop()
          ?.trim()
        if (!clean) return false
        return new RegExp(`\\b${escapeRegExp(clean)}\\b`).test(inner)
      })

    if (specifiers.length > 0) {
      const joined =
        specifiers.length > 3
          ? `{\n  ${specifiers.join(',\n  ')},\n}`
          : `{ ${specifiers.join(', ')} }`
      imports.push(`import ${joined} from '${mod}'`)
    }
  }

  const indentedBody = inner
    .split('\n')
    .map((line) => (line ? `    ${line}` : ''))
    .join('\n')

  const needsFragment =
    /^<[A-Za-z]/.test(inner) &&
    (inner.match(/\n<[A-Za-z]/g)?.length ?? 0) > 0 &&
    !inner.startsWith('<>')

  const wrapped = needsFragment
    ? `export function Example() {\n  return (\n    <>\n${indentedBody}\n    </>\n  )\n}`
    : `export function Example() {\n  return (\n${indentedBody}\n  )\n}`

  return imports.length > 0 ? `${imports.join('\n')}\n\n${wrapped}` : wrapped
}

